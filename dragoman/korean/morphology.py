@functools.lru_cache(maxsize=50000)
def gloss(lemma, pos):
    """見出し語 → (訳, 'ja' / 'en', 辞書の項目)。日本語に直せなければ英語の語義のまま"""
    from dragoman.core import en_ja
    poses = {'noun': ('noun', 'name', 'pronoun', 'num', 'counter'), 'name': ('name', 'noun'), 'verb': ('verb', 'adj'),
             'adj': ('adj', 'verb'), 'adv': ('adv', 'noun')}.get(pos, (pos,))
    rows = dictionary.lemmas(lemma, poses)
    if pos == 'name':   # 固有名詞は name の項目を先に (서울 → Seoul。noun の「首都」でなく)
        rows = dictionary.lemmas(lemma, ('name',)) or rows
    row = rows[0] if rows else None
    if lemma in GLOSSES:
        return GLOSSES[lemma], 'ja', row
    if row is None:
        return None, None, None
    if row['pos'] == 'name' and pos in ('name', 'noun'):
        name = row['en'].split(',')[0]
        return (en_ja.translate(name, 'noun') or name), 'ja' if en_ja.translate(name, 'noun') else 'en', row
    ja = en_ja.translate(row['en'], 'adj' if pos == 'adj' else pos, limit=2) if pos in ('noun', 'verb', 'adj', 'adv') else None
    if ja:
        return ja, 'ja', row
    return row['en'], 'en', row


def describe(lemma, row):
    """見出しの表示: 학교 (學校) hakgyo"""
    roman = (row or {}).get('roman') or script.romanize(lemma)
    hanja = (row or {}).get('hanja')
    return '%s%s %s' % (lemma, ' (%s)' % hanja if hanja else '', roman)


def roman(surface):
    return script.romanize(surface)


def is_adjective(lemma):
    """形容詞 (状態の用言) か: 辞書の品詞が adj だけのもの"""
    poses = {r['pos'] for r in dictionary.lemmas(lemma, ('adj', 'verb'))}
    return poses == {'adj'} or lemma in ('좋다', '나쁘다', '크다', '작다', '많다', '적다', '예쁘다', '맛있다', '재미있다', '아프다',
                                          '덥다', '춥다', '높다', '길다', '짧다', '멀다', '가깝다', '바쁘다', '아름답다', '빠르다',
                                          '느리다', '없다')


def japanese_verb_stem(ja):
    """訳語の最初の語 (「読む,学ぶ」→「読む」)"""
    return (ja or '').split(',')[0]


def attach(verb, suffix):
    from dragoman.core.japanese import attach_auxiliary
    return attach_auxiliary(verb, suffix)
