@functools.lru_cache(maxsize=1)
def nlp():
    import spacy
    return spacy.load('zh_core_web_sm')


def available():
    try:
        nlp()
    except (ImportError, OSError):
        return False
    return dictionary.available()


def parse(words):
    """語の列 → spaCy の Doc (語の切れ目はそのまま)"""
    from spacy.tokens import Doc
    model = nlp()
    return model(Doc(model.vocab, words=list(words)))


@functools.lru_cache(maxsize=50000)
def gloss(word, pos):
    """語 → (訳, 'ja' / 'en', 辞書の項目)"""
    from dragoman.core import en_ja
    rows = dictionary.lookup(word)
    row = rows[0] if rows else None
    if word in GLOSSES:
        return GLOSSES[word], 'ja', row
    if row is None or not row['en']:
        return None, None, row
    ja = en_ja.translate(row['en'], pos if pos in ('noun', 'verb', 'adj', 'adv') else 'noun', limit=2)
    return (ja, 'ja', row) if ja else (row['en'].split(',')[0], 'en', row)


def pinyin(word):
    """語の拼音 (数字の声調: shu1)。pypinyin (熟語の読みと字のよく使う読み: 了 → le5、长大 → zhang3 da4) を先に、
    無ければ辞書 (CC-CEDICT。語義の順はよく使う順でないので後に)"""
    try:
        from pypinyin import lazy_pinyin, Style
        out = lazy_pinyin(word, style=Style.TONE3, neutral_tone_with_five=True, errors='ignore')
        if out:
            return ' '.join(out)
    except ImportError:
        pass
    rows = [r for r in dictionary.lookup(word) if not r['proper']] or list(dictionary.lookup(word))
    return rows[0]['pinyin'] if rows else ''


def adverbial(ja):
    """形容詞の訳 → 副詞の形 (速い → 速く、静かな → 静かに)"""
    out = []
    for j in ja.split(','):
        if j.endswith('い') and not j.endswith(('きれい', 'きらい')):
            out.append(j[:-1] + 'く')
        elif j.endswith(('な', 'の')):
            out.append(j[:-1] + 'に')
        else:
            out.append(j + 'に')
    return ','.join(out)
